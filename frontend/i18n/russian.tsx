const patterns: [RegExp, (...parts: string[]) => string][] = [
  [/^Step (\d+) of (\d+): (.+)$/, (step, total, title) =>
    `Шаг ${step} из ${total}: ${translateToRussian(title)}`],
  [/^(\d+) years old$/, age => `${age} лет`],
  [/^(\d+) miles? away$/, distance => `${distance} миль`],
  [/^(\d+) kilometers? away$/, distance => `${distance} км`],
];

const translateToRussian = (value: string): string => {
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const text = value.trim();
  const exact = translations[text];
  if (exact) return leading + exact + trailing;

  for (const [pattern, replacement] of patterns) {
    const match = text.match(pattern);
    if (match) return leading + replacement(...match.slice(1)) + trailing;
  }

  return value;
};

const translateNodeToRussian = (node: ReactNode): ReactNode => {
  if (typeof node === 'string') return translateToRussian(node);
  if (Array.isArray(node)) return node.map(translateNodeToRussian);
  return node;
};

export { translateNodeToRussian, translateToRussian };
